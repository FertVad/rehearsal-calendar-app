-- 010: proof that a person controls their sign-in address (R3: A01, HP01).
--
-- No row in native_email_identities is an account from before this step: it
-- keeps working, but its address is not treated as proven. Nothing here marks
-- existing addresses verified.
--
-- A code is stored only as an HMAC. One live code per person and purpose; a
-- resend consumes the previous one first. sent_at/failed_at record what the
-- mail provider said, after the transaction that created the code committed.

CREATE TABLE native_email_identities (
  user_id INTEGER PRIMARY KEY REFERENCES native_users(id) ON DELETE CASCADE,
  email TEXT NOT NULL,
  status TEXT NOT NULL CHECK (status IN ('pending', 'verified')),
  verified_at TIMESTAMPTZ,
  verified_by TEXT CHECK (verified_by IN ('code', 'google', 'apple')),
  created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  CHECK ((status = 'verified') = (verified_at IS NOT NULL AND verified_by IS NOT NULL))
);

CREATE TABLE native_email_codes (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id INTEGER NOT NULL REFERENCES native_users(id) ON DELETE CASCADE,
  purpose TEXT NOT NULL CHECK (purpose IN ('verify', 'reset', 'change', 'confirm')),
  email TEXT NOT NULL,
  code_hash TEXT NOT NULL CHECK (code_hash ~ '^[0-9a-f]{64}$'),
  attempts INTEGER NOT NULL DEFAULT 0 CHECK (attempts BETWEEN 0 AND 5),
  expires_at TIMESTAMPTZ NOT NULL,
  consumed_at TIMESTAMPTZ,
  sent_at TIMESTAMPTZ,
  failed_at TIMESTAMPTZ,
  created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);
CREATE UNIQUE INDEX idx_email_codes_live ON native_email_codes (user_id, purpose) WHERE consumed_at IS NULL;
CREATE INDEX idx_email_codes_recent ON native_email_codes (user_id, purpose, created_at);
