-- Canonical PostgreSQL schema for an explicitly verified EMPTY application schema.
-- Run through the migration CLI: one transaction owns DDL, catalog checks and history.
-- No table drops, legacy rewrites, implicit environment loading or runtime startup.
-- PostgreSQL int4 IDs keep the existing numeric API contract. All timestamps are
-- instants (TIMESTAMPTZ); only project calendar dates use DATE.
-- Historical migrations remain immutable archives; this snapshot does not claim
-- they were executed. Existing databases require a named, verified adoption profile.

CREATE TABLE native_users (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  email VARCHAR UNIQUE NOT NULL,
  password_hash VARCHAR,
  first_name VARCHAR NOT NULL,
  last_name VARCHAR,
  phone VARCHAR(50),
  avatar_url TEXT,
  timezone VARCHAR DEFAULT 'UTC',
  locale VARCHAR DEFAULT 'en',
  week_start_day VARCHAR(10) DEFAULT 'monday',
  notifications_enabled BOOLEAN DEFAULT TRUE,
  email_notifications BOOLEAN DEFAULT TRUE,
  onboarding_completed BOOLEAN DEFAULT FALSE,
  token_version INTEGER NOT NULL DEFAULT 1,
  last_login_at TIMESTAMPTZ,
  created_at TIMESTAMPTZ DEFAULT CURRENT_TIMESTAMP,
  updated_at TIMESTAMPTZ DEFAULT CURRENT_TIMESTAMP,
  telegram_id BIGINT,
  push_token TEXT
);

CREATE TABLE native_auth_providers (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id INTEGER NOT NULL,
  provider_type VARCHAR(20) NOT NULL,
  provider_user_id VARCHAR(255),
  provider_email VARCHAR(255),
  provider_metadata TEXT,
  created_at TIMESTAMPTZ NOT NULL,
  updated_at TIMESTAMPTZ NOT NULL,
  last_used_at TIMESTAMPTZ,
  FOREIGN KEY (user_id) REFERENCES native_users(id) ON DELETE CASCADE,
  UNIQUE(provider_type, provider_user_id),
  CHECK (provider_type IN ('email', 'google', 'apple'))
);

CREATE TABLE native_projects (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name VARCHAR NOT NULL,
  description TEXT,
  timezone VARCHAR NOT NULL DEFAULT 'UTC',
  invite_code VARCHAR(32) UNIQUE,
  invite_expires_at TIMESTAMPTZ,
  invite_created_by INTEGER,
  created_at TIMESTAMPTZ DEFAULT CURRENT_TIMESTAMP,
  updated_at TIMESTAMPTZ DEFAULT CURRENT_TIMESTAMP,
  color VARCHAR(7) DEFAULT '#A855F7',
  start_date DATE,
  end_date DATE,
  premiere_date DATE,
  status VARCHAR(20) DEFAULT 'active',
  FOREIGN KEY (invite_created_by) REFERENCES native_users(id) ON DELETE SET NULL
);

CREATE TABLE native_project_members (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id INTEGER NOT NULL,
  project_id INTEGER NOT NULL,
  role VARCHAR NOT NULL DEFAULT 'member',
  status VARCHAR NOT NULL DEFAULT 'active',
  invited_at TIMESTAMPTZ,
  joined_at TIMESTAMPTZ,
  created_at TIMESTAMPTZ DEFAULT CURRENT_TIMESTAMP,
  character_name VARCHAR(100),
  invite_code VARCHAR(32),
  expires_at TIMESTAMPTZ,
  FOREIGN KEY (user_id) REFERENCES native_users(id) ON DELETE CASCADE,
  FOREIGN KEY (project_id) REFERENCES native_projects(id) ON DELETE CASCADE,
  UNIQUE(user_id, project_id)
);

CREATE TABLE native_rehearsals (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  project_id INTEGER NOT NULL,
  title VARCHAR,
  description TEXT,
  starts_at TIMESTAMPTZ NOT NULL,
  ends_at TIMESTAMPTZ NOT NULL,
  location VARCHAR,
  created_by INTEGER,
  created_at TIMESTAMPTZ DEFAULT CURRENT_TIMESTAMP,
  updated_at TIMESTAMPTZ DEFAULT CURRENT_TIMESTAMP,
  location_address TEXT,
  location_notes TEXT,
  status VARCHAR(20) DEFAULT 'scheduled',
  recurrence_rule TEXT,
  parent_rehearsal_id INTEGER,
  is_all_day BOOLEAN DEFAULT FALSE,
  FOREIGN KEY (project_id) REFERENCES native_projects(id) ON DELETE CASCADE,
  FOREIGN KEY (created_by) REFERENCES native_users(id) ON DELETE SET NULL,
  CHECK (ends_at > starts_at)
);

CREATE TABLE native_rehearsal_responses (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
