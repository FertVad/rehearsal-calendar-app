// The admin page sets project names in quotes the way the app does (T-419):
// shared/quoteName.cjs, the one implementation. The page is a plain script under
// public/admin/, so the module is copied there wrapped for the browser — public/
// is what the deployment carries (vercel.json, includeFiles), shared/ is not
// read at runtime. adminQuoteName.test.js fails when the copy is behind its
// source: run `npm run build:admin-quote-name` in server/ after editing it.
import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';

export const sourcePath = fileURLToPath(new URL('../../shared/quoteName.cjs', import.meta.url));
export const scriptPath = fileURLToPath(new URL('../public/admin/quoteName.js', import.meta.url));

/** The browser script: the CommonJS module run in its own scope, its function on window. */
export function quoteNameScript(source) {
  return '// Generated by server/scripts/admin-quote-name.mjs from shared/quoteName.cjs. Do not edit.\n'
    + '(() => {\n  const module = { exports: {} };\n'
    + source
    + '\n  window.adminQuoteName = module.exports.quoteName;\n})();\n';
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  writeFileSync(scriptPath, quoteNameScript(readFileSync(sourcePath, 'utf8')));
  console.log('Wrote ' + scriptPath);
}
