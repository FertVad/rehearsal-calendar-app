// The admin users listing (T-293) reads where each person came from and how far
// they got: membership dates, sign-in methods, marks and calendars. The R0
// diagnostic subset (fixture.sql) has none of these, so a scenario that lists
// users after a real admin login adds exactly them, in the shapes of
// database/init-native-schema.sql. native_users columns stay with each scenario.
export async function addAdminListingSchema(control) {
  await control.query(`
    ALTER TABLE native_project_members ADD COLUMN IF NOT EXISTS created_at TIMESTAMPTZ DEFAULT CURRENT_TIMESTAMP;
    ALTER TABLE native_user_availability ADD COLUMN IF NOT EXISTS created_at TIMESTAMPTZ DEFAULT CURRENT_TIMESTAMP;
    CREATE TABLE IF NOT EXISTS native_auth_providers (
      id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
      user_id INTEGER NOT NULL REFERENCES native_users(id) ON DELETE CASCADE,
      provider_type VARCHAR(20) NOT NULL, provider_user_id VARCHAR(255), provider_email VARCHAR(255),
      provider_metadata TEXT, created_at TIMESTAMPTZ NOT NULL, updated_at TIMESTAMPTZ NOT NULL,
      last_used_at TIMESTAMPTZ, UNIQUE(provider_type, provider_user_id),
      CHECK (provider_type IN ('email', 'google', 'apple')));
    CREATE TABLE IF NOT EXISTS native_calendar_connections (
      id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
      user_id INTEGER NOT NULL REFERENCES native_users(id) ON DELETE CASCADE,
      provider VARCHAR NOT NULL, calendar_id VARCHAR, device_calendar_id VARCHAR,
      created_at TIMESTAMPTZ DEFAULT CURRENT_TIMESTAMP,
      CHECK (calendar_id IS NOT NULL OR device_calendar_id IS NOT NULL));`);
}
