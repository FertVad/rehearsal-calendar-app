import assert from 'node:assert/strict';
import pg from 'pg';
export const quote = value => {
  assert.match(value, /^fm_[a-z0-9_]+$/);
  return `"${value}"`;
};
export async function connect() {
  const url = new URL(process.env.FM_DATABASE_URL);
  assert.equal(url.hostname, '127.0.0.1');
  assert.equal(url.pathname, '/legacy_fixture');
  assert.match(process.env.FM_NONCE, /^[a-f0-9]{24}$/);
  const client = new pg.Client({ connectionString: url.href, connectionTimeoutMillis: 2000,
    statement_timeout: 10000, query_timeout: 12000, application_name: 'fm_owned_probe' });
  client.on('error', () => {});
  await client.connect();
  assert.deepEqual((await client.query('SELECT nonce FROM public.r2_legacy_owned')).rows, [{ nonce: process.env.FM_NONCE }]);
  return client;
}
