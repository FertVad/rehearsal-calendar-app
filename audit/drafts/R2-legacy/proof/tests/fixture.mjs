export async function rows(client, table) {
  assert.match(table, /^native_[a-z_]+$/);
  return (await client.query(`SELECT to_jsonb(t) AS row FROM ${table} t ORDER BY id`)).rows.map(({row}) => row);
}
export function cases() {
  let passed = 0, failed = 0;
  return {
    async run(name, fn) {
      try { await fn(); passed++; console.log(JSON.stringify({name,outcome:'PASS'})); }
      catch(error) { failed++; console.log(JSON.stringify({name,outcome:'FAIL',code:error.code || 'ASSERTION', detail:'desired contract did not hold'})); }
    },
    finish() { console.log(JSON.stringify({passed,failed,outcome:failed?'FAIL':'PASS'})); process.exitCode = failed ? 1 : 0; }
  };
}
