// T-225: builds the checks in check/ from the real subflows, so they differ
// from them in one tap only.
//
//   node audit/evidence/T-225/make-checks.mjs <base commit>
//
// - sign-in-form-no-submit.yaml: sign-in-form.yaml as it was at <base>, its
//   tap on "Sign In" taken out - what a lost tap on it leaves.
// - tap-and-see-first-lost.yaml: tap-and-see.yaml as it is now, its first tap
//   taken out - what a lost first tap leaves it.
// - sign-in-form-first-lost.yaml: sign-in-form.yaml as it is now, tapping
//   "Sign In" through tap-and-see-first-lost.yaml.
import { execFileSync } from 'node:child_process';
import fs from 'node:fs';
import path from 'node:path';

process.chdir(new URL('../../..', import.meta.url).pathname);
const base = process.argv[2];
if (!base) throw new Error('usage: make-checks.mjs <base commit>');
const sub = 'rehearsal-calendar-native/e2e/subflows';
const out = path.join('audit/evidence/T-225/check');
const real = '../../../../rehearsal-calendar-native/e2e';
const head = '# Generated by audit/evidence/T-225/make-checks.mjs - do not edit.\n';
const swap = (text, from, to) => {
  if (!text.includes(from)) throw new Error(`not found: ${from.slice(0, 60)}`);
  return text.replace(from, to);
};

const oldForm = execFileSync('git', ['show', `${base}:${sub}/sign-in-form.yaml`], {
  encoding: 'utf8',
});
let noSubmit = swap(oldForm, '- tapOn:\n    id: login-submit\n', '');
noSubmit = swap(noSubmit, 'file: tap-and-see.yaml', `file: ${real}/subflows/tap-and-see.yaml`);
fs.writeFileSync(path.join(out, 'sign-in-form-no-submit.yaml'), head + noSubmit);

const tapAndSee = fs.readFileSync(path.join(sub, 'tap-and-see.yaml'), 'utf8');
const firstTap = tapAndSee.slice(
  tapAndSee.indexOf('---\n') + 4,
  tapAndSee.indexOf('# Asked as "is it there"'),
);
let firstLost = swap(tapAndSee, firstTap, '');
firstLost = swap(firstLost, 'file: ../scripts/tap-again.js', `file: ${real}/scripts/tap-again.js`);
fs.writeFileSync(path.join(out, 'tap-and-see-first-lost.yaml'), head + firstLost);

const newForm = fs.readFileSync(path.join(sub, 'sign-in-form.yaml'), 'utf8');
const submit = newForm.indexOf('    TAP_ID: login-submit');
const before = newForm.lastIndexOf('file: tap-and-see.yaml', submit);
let formFirstLost =
  newForm.slice(0, before) + 'file: tap-and-see-first-lost.yaml' +
  newForm.slice(before + 'file: tap-and-see.yaml'.length);
formFirstLost = swap(formFirstLost, 'file: tap-and-see.yaml', `file: ${real}/subflows/tap-and-see.yaml`);
fs.writeFileSync(path.join(out, 'sign-in-form-first-lost.yaml'), head + formFirstLost);
console.log('written:', fs.readdirSync(out).join(', '));
